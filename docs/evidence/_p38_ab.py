def _run_one(text: str, derive: bool) -> tuple[str, str, str]:
    """返回（等级 / signal / why）；规则命中或路径失败都如实标出。"""
    pre = guardian.guardian_pre_check(text)
    if pre["level"] != "L1" or pre["rule_ids"]:
        return pre["level"], "-", "规则:" + ",".join(pre["rule_ids"])
    got = risk_review.derive(text) if derive else risk_review.judge(text)
    if not got.get("ok"):
        return "L1", got.get("signal", "-"), "模型没答"
    return got["level"], got.get("signal", "-"), got.get("why", "")


def _tally(rows: list[tuple[str, str]]) -> tuple[int, int]:
    return sum(1 for lv, _ in rows if lv == "L3"), sum(1 for lv, _ in rows if lv in ("L2", "L3"))


