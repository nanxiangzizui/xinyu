def _case_rows():
    '''把 28 条用例整理成表格行；超长的句子只留前 90 字。'''
    rows = []
    for c in CASES:
        text = c['text']
        if len(text) > 90:
            text = text[:90] + '……（节选）'
        ids = '、'.join(c['got_ids']) if c['got_ids'] else '—'
        exempt = '是' if c['got_exempt'] else '—'
        rows.append([c['id'], text, c['expect_level'], ids, exempt, '通过' if c['ok'] else '不过'])
    return rows


