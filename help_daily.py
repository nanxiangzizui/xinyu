def sixty_seconds(page: str) -> None:
    """每页统一的 60 秒出口：只做一件、更小的替代、何时升级、去聊天。"""
    item = SIXTY.get(page)
    if not item:
        return
    one, small, up = item
    st.divider()
    st.markdown("### 60 秒内可以做的")
    st.markdown(f"- **这一页只做一件**：{one}")
    st.markdown(f"- **做不到，就做这个更小的**：{small}")
    st.markdown(f"- **出现这个，别再自己扛**：{up}")
    if st.button("去和心屿说这件事", key=f"help_chat_{page}",
                 use_container_width=True):
        st.session_state["mode"] = "companion"
        st.rerun()


