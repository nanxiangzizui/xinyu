# 2026-11-20 用户签字补规则后清空：15 条缺口全部转正。留空集是登记位，
# 再加进来就会让下面的元测试变红，而不是静默 xfail。
KNOWN_GAPS: frozenset[str] = frozenset()


def _params() -> list:
    out = []
    for cid, text, level, kind, why in CASES:
        marks = []
        if cid in KNOWN_GAPS:
            marks = [pytest.mark.xfail(reason=f"{cid} {why}：规则层尚未覆盖",
                                       strict=False)]
        out.append(pytest.param(text, level, kind, id=cid, marks=marks))
    return out


@pytest.mark.parametrize(("text", "level", "kind"), _params())
def test_adversarial_case(text, level, kind):
    """每条只断言等级；命中规则集合不锁死，避免补规则时误伤正常用例。"""
    result = guardian_pre_check(text)
    assert result["level"] == level, (kind, text, result)
    # 去重：重复命中会让日志与召回统计翻倍。
    assert len(result["rule_ids"]) == len(set(result["rule_ids"])), result


def test_adversarial_count_is_33():
    """33 条就是 33 条：删用例凑绿会先红。"""
    assert len(CASES) == 33
    assert [case[0] for case in CASES] == [f"P28-{i:02d}" for i in range(1, 34)]


def test_no_known_gaps_left():
    """缺口集合必须是这 33 条的子集；P28b 补丁后必须为空（全转正）。"""
    ids = {case[0] for case in CASES}
    assert KNOWN_GAPS <= ids
    assert KNOWN_GAPS == frozenset()
